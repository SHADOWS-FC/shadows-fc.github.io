function latinizeGreekWord(word) {
  if (latinNames[word]) return latinNames[word];
  const plain = word.normalize('NFD').replace(/\p{M}/gu, '');
  const latin = plain.toLowerCase().replace(/ου|αι|ει|οι|αυ|ευ|γγ|γκ|μπ|ντ|τσ|τζ|[α-ω]/g, letters => greekLetters[letters] || letters);
  return plain === plain.toUpperCase() ? latin.toUpperCase()
    : plain[0] === plain[0].toUpperCase() ? latin[0].toUpperCase() + latin.slice(1) : latin;
}
export function localizedName(name, language = 'el') {
  if (language !== 'el') return name.replace(/\p{Script=Greek}+/gu, latinizeGreekWord);
  return name.replace(/[A-Za-z]+/g, word => greekNames[word] || word);
}
